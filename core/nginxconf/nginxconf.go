// Package nginxconf renders nginx.conf from sites and PHP pools.
//
// Every path is quoted and uses forward slashes, so roots with spaces
// (C:\Users\Jane Doe\ebur) work; this was checked in spikes/phppool.
package nginxconf

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/ebur/ebur/core/php"
	"github.com/ebur/ebur/core/sites"
)

type Config struct {
	NginxDir string // nginx install, for mime.types and fastcgi_params
	LogDir   string
	TempDir  string
	PIDFile  string
	Listen   string // e.g. "127.0.0.1:80" (NFR-07: loopback by default)
	Sites    []sites.Site
	Pool     php.Pool // PHP pool every site uses (per-site pools come with PHP-04)
}

func q(path string) string {
	return `"` + strings.ReplaceAll(filepath.ToSlash(path), `"`, `\"`) + `"`
}

// Render returns the full nginx.conf.
func Render(c Config) string {
	var b strings.Builder
	upstream := strings.ReplaceAll(c.Pool.Name(), ".", "_")
	fmt.Fprintf(&b, `# Generated by Ebur. Edits are overwritten; change templates\ instead.
worker_processes 1;
error_log %s warn;
pid %s;

events { worker_connections 1024; }

http {
    include %s;
    default_type application/octet-stream;
    sendfile off;
    client_max_body_size 512m;
    access_log %s;
    client_body_temp_path %s;
    fastcgi_temp_path %s;
    proxy_temp_path %s;
    uwsgi_temp_path %s;
    scgi_temp_path %s;

`,
		q(filepath.Join(c.LogDir, "nginx-error.log")), q(c.PIDFile),
		q(filepath.Join(c.NginxDir, "conf", "mime.types")),
		q(filepath.Join(c.LogDir, "nginx-access.log")),
		q(filepath.Join(c.TempDir, "body")), q(filepath.Join(c.TempDir, "fastcgi")),
		q(filepath.Join(c.TempDir, "proxy")), q(filepath.Join(c.TempDir, "uwsgi")), q(filepath.Join(c.TempDir, "scgi")))

	for _, line := range strings.Split(strings.TrimRight(c.Pool.NginxUpstream(), "\n"), "\n") {
		b.WriteString("    " + line + "\n")
	}

	fmt.Fprintf(&b, `
    # Unknown host names get a clear message instead of a random site.
    server {
        listen %s default_server;
        server_name _;
        default_type text/plain;
        return 404 "Ebur: no site matches this host name. Create a folder in www\\ named after it.\n";
    }
`, c.Listen)

	params := q(filepath.Join(c.NginxDir, "conf", "fastcgi_params"))
	for _, s := range c.Sites {
		fmt.Fprintf(&b, `
    server {
        listen %s;
        server_name %s;
        root %s;
        index index.php index.html index.htm;
        charset utf-8;

        location / {
            try_files $uri $uri/ /index.php?$query_string;
        }

        location ~ \.php$ {
            try_files $uri =404;
            include %s;
            fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
            fastcgi_next_upstream error timeout;
            fastcgi_read_timeout 300s;
            fastcgi_pass %s;
        }

        location ~ /\.(?!well-known) { deny all; }
    }
`, c.Listen, s.Host, q(s.DocRoot), params, upstream)
	}
	b.WriteString("}\n")
	return b.String()
}
