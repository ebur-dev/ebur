// Package nginxconf renders nginx.conf from sites and PHP pools.
//
// Every path is quoted and uses forward slashes, so roots with spaces
// (C:\Users\Jane Doe\ebur) work; this was checked in spikes/phppool.
package nginxconf

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/ebur-dev/ebur/core/php"
	"github.com/ebur-dev/ebur/core/sites"
)

type Config struct {
	NginxDir string // nginx install, for mime.types and fastcgi_params
	LogDir   string
	TempDir  string
	PIDFile  string
	Listen   string // e.g. "127.0.0.1:80" (NFR-07: loopback by default)
	Sites    []sites.Site
	// Pools has one php-cgi pool per PHP version in use; the first is the
	// default. Each site is sent to the pool for its Site.PHP.Version
	// (PHP-04), or to the default pool.
	Pools []php.Pool
	// Proxies forward a host name to a local web UI, e.g. mail.test to
	// Mailpit (TOOL-03).
	Proxies []Proxy

	// Shares serve one site each on a private loopback port, for a
	// Cloudflare quick tunnel (TOOL-04).
	Shares []ShareServer

	// HTTPS (SSL-02). Empty TLSListen means HTTP only.
	TLSListen string             // e.g. "127.0.0.1:443"
	TLS       map[string]TLSPair // host -> certificate files
	CRLFile   string             // served at certs.CRLPath on the default server
	CRLPath   string
}

// TLSPair is a certificate chain and its key.
type TLSPair struct{ Cert, Key string }

// Proxy serves Host by forwarding to Target, e.g. "127.0.0.1:8025".
type Proxy struct{ Host, Target string }

// ShareServer serves Site on Listen (e.g. "127.0.0.1:8180") for a share
// tunnel. Htpasswd, when set, asks visitors for a password.
type ShareServer struct {
	Site     sites.Site
	Listen   string
	Htpasswd string
}

func q(path string) string {
	return `"` + strings.ReplaceAll(filepath.ToSlash(path), `"`, `\"`) + `"`
}

func upstreamName(p php.Pool) string { return strings.ReplaceAll(p.Name(), ".", "_") }

// upstreamFor returns the pool upstream serving a site.
func (c Config) upstreamFor(s sites.Site) string {
	for _, p := range c.Pools {
		if p.Version == s.PHP.Version {
			return upstreamName(p)
		}
	}
	if len(c.Pools) == 0 {
		return "php-missing"
	}
	return upstreamName(c.Pools[0])
}

// tlsFor returns the HTTPS listen lines for host, or "" without a cert.
func (c Config) tlsFor(host string) string {
	pair, ok := c.TLS[host]
	if !ok || c.TLSListen == "" {
		return ""
	}
	return fmt.Sprintf("        listen %s ssl;\n        http2 on;\n        ssl_certificate %s;\n        ssl_certificate_key %s;\n",
		c.TLSListen, q(pair.Cert), q(pair.Key))
}

// Render returns the full nginx.conf.
func Render(c Config) string {
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by Ebur. Edits are overwritten; change templates\ instead.
worker_processes 1;
error_log %s warn;
pid %s;

events { worker_connections 1024; }

http {
    include %s;
    default_type application/octet-stream;
    sendfile off;
    client_max_body_size 512m;
    access_log %s;
    client_body_temp_path %s;
    fastcgi_temp_path %s;
    proxy_temp_path %s;
    uwsgi_temp_path %s;
    scgi_temp_path %s;

`,
		q(filepath.Join(c.LogDir, "nginx-error.log")), q(c.PIDFile),
		q(filepath.Join(c.NginxDir, "conf", "mime.types")),
		q(filepath.Join(c.LogDir, "nginx-access.log")),
		q(filepath.Join(c.TempDir, "body")), q(filepath.Join(c.TempDir, "fastcgi")),
		q(filepath.Join(c.TempDir, "proxy")), q(filepath.Join(c.TempDir, "uwsgi")), q(filepath.Join(c.TempDir, "scgi")))

	for _, p := range c.Pools {
		for _, line := range strings.Split(strings.TrimRight(p.NginxUpstream(), "\n"), "\n") {
			b.WriteString("    " + line + "\n")
		}
	}

	tlsDefault := ""
	if c.TLSListen != "" {
		// Unknown names over HTTPS are refused at the handshake instead of
		// being shown another site's certificate.
		tlsDefault = fmt.Sprintf("        listen %s ssl default_server;\n        ssl_reject_handshake on;\n", c.TLSListen)
	}
	crl := ""
	if c.CRLFile != "" {
		// Schannel (curl.exe) needs a reachable CRL for local certificates.
		crl = fmt.Sprintf("\n        location = %s {\n            alias %s;\n            default_type application/pkix-crl;\n        }\n", c.CRLPath, q(c.CRLFile))
	}
	fmt.Fprintf(&b, `
    # Unknown host names get a clear message instead of a random site.
    server {
        listen %s default_server;
%s        server_name _;
        default_type text/plain;
%s
        location / {
            return 404 "Ebur: no site matches this host name. Create a folder in www\\ named after it.\n";
        }
    }
`, c.Listen, tlsDefault, crl)

	params := q(filepath.Join(c.NginxDir, "conf", "fastcgi_params"))
	for _, s := range c.Sites {
		tls := c.tlsFor(s.Host)
		fmt.Fprintf(&b, `
    server {
        listen %s;
%s        server_name %s;
        root %s;
        index index.php index.html index.htm;
        charset utf-8;

        location / {
            try_files $uri $uri/ /index.php?$query_string;
        }

        location ~ \.php$ {
            try_files $uri =404;
            include %s;
            fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
            fastcgi_next_upstream error timeout;
            fastcgi_read_timeout 300s;
            fastcgi_pass %s;
        }

        location ~ /\.(?!well-known) { deny all; }
    }
`, c.Listen, tls, s.Host, q(s.DocRoot), params, c.upstreamFor(s))
	}
	for _, sh := range c.Shares {
		auth := ""
		if sh.Htpasswd != "" {
			auth = fmt.Sprintf("        auth_basic \"Ebur share: %s\";\n        auth_basic_user_file %s;\n", sh.Site.Name, q(sh.Htpasswd))
		}
		// Only this site is reachable through the tunnel: the listener is
		// loopback-only and serves nothing else. PHP is told the visit is
		// HTTPS (Cloudflare ends TLS), so frameworks build https:// links
		// to the share address; APP_DEBUG is forced off because Laravel and
		// Symfony debug pages can show secrets to strangers; EBUR_SHARE
		// lets the WordPress helper plugin recognise shared visits.
		fmt.Fprintf(&b, `
    # Share of %s (ebur share): only reached through its tunnel.
    server {
        listen %s;
        server_name _;
        root %s;
        index index.php index.html index.htm;
        charset utf-8;
%s
        location / {
            try_files $uri $uri/ /index.php?$query_string;
        }

        location ~ \.php$ {
            try_files $uri =404;
            include %s;
            fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
            fastcgi_param HTTPS on;
            fastcgi_param REQUEST_SCHEME https;
            fastcgi_param SERVER_PORT 443;
            fastcgi_param APP_DEBUG false;
            fastcgi_param EBUR_SHARE 1;
            fastcgi_next_upstream error timeout;
            fastcgi_read_timeout 300s;
            fastcgi_pass %s;
        }

        location ~ /\.(?!well-known) { deny all; }
    }
`, sh.Site.Name, sh.Listen, q(sh.Site.DocRoot), auth, params, c.upstreamFor(sh.Site))
	}
	for _, p := range c.Proxies {
		fmt.Fprintf(&b, `
    server {
        listen %s;
%s        server_name %s;

        location / {
            proxy_pass http://%s;
            proxy_http_version 1.1;
            # Live updates use a WebSocket.
            proxy_set_header Upgrade $http_upgrade;
            proxy_set_header Connection "upgrade";
            proxy_set_header Host $host;
            proxy_read_timeout 1h;
            proxy_buffering off;
        }
    }
`, c.Listen, c.tlsFor(p.Host), p.Host, p.Target)
	}
	b.WriteString("}\n")
	return b.String()
}
