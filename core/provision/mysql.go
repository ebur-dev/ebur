// prepareMySQL sets up an installed MySQL next to MariaDB (SVC-01): a port
// of its own, the shared root password, a trimmed install, my.ini, and on
// first use a data folder.
func prepareMySQL(ctx context.Context, root paths.Root, dir, version string, say func(string)) (Report, error) {
	var rep Report
	cfg, err := config.Load(root.Config())
	if err != nil {
		return rep, err
	}
	changed := false
	if cfg.DBRootPassword == "" {
		pw, err := password(20)
		if err != nil {
			return rep, err
		}
		cfg.DBRootPassword, changed = pw, true
		rep.Steps = append(rep.Steps, "generated a database root password (see `ebur db`)")
	}
	if cfg.MySQLPort == 0 {
		cfg.MySQLPort, changed = PickMySQLPort(MariaDBPortInUse(root, cfg)), true
		rep.Steps = append(rep.Steps, fmt.Sprintf("MySQL will use port %d", cfg.MySQLPort))
	}
	if changed {
		if err := config.Save(root.Config(), cfg); err != nil {
			return rep, err
		}
	}
	if freed, err := TrimMySQL(dir); err != nil {
		rep.Warnings = append(rep.Warnings, "could not remove MySQL's debug files: "+err.Error())
	} else if freed > 0 {
		rep.Steps = append(rep.Steps, fmt.Sprintf("removed %d MB of MySQL debug and developer files", freed>>20))
	}
	ini, err := WriteMySQLIni(root, version, cfg.MySQLPort)
	if err != nil {
		return rep, err
	}
	if _, err := WriteClientCnf(root, dbserver.MySQL, version, cfg.MySQLPort, cfg.DBRootPassword); err != nil {
		return rep, err
	}
	dataDir, _ := dbserver.Paths(root, dbserver.MySQL, version)
	if _, err := os.Stat(filepath.Join(dataDir, "mysql")); err == nil {
		rep.Steps = append(rep.Steps, "reusing existing databases in "+dataDir)
		return rep, nil
	}
	say("Creating the MySQL data folder (first run can take a minute under antivirus)...")
	if err := os.MkdirAll(filepath.Dir(dataDir), 0o755); err != nil {
		return rep, err
	}
	// --initialize-insecure creates root@localhost without a password; the
	// init file then sets Ebur's password and adds root@127.0.0.1, which
	// TCP connections from PHP use.
	initSQL := filepath.Join(filepath.Dir(ini), "ebur-init.sql")
	pw := cfg.DBRootPassword // generated: letters and digits only
	sql := fmt.Sprintf("ALTER USER 'root'@'localhost' IDENTIFIED BY '%s';\nCREATE USER IF NOT EXISTS 'root'@'127.0.0.1' IDENTIFIED BY '%s';\nGRANT ALL PRIVILEGES ON *.* TO 'root'@'127.0.0.1' WITH GRANT OPTION;\n", pw, pw)
	if err := os.WriteFile(initSQL, []byte(sql), 0o600); err != nil {
		return rep, err
	}
	defer os.Remove(initSQL)
	daemon := filepath.Join(dir, "bin", "mysqld.exe")
	out, err := run(ctx, daemon, "--defaults-file="+filepath.ToSlash(ini), "--initialize-insecure",
		"--init-file="+filepath.ToSlash(initSQL), "--console")
	if err != nil {
		os.RemoveAll(dataDir) // never leave a half-initialised data folder
		hint := ""
		if strings.Contains(out, "MSVCP120") || strings.Contains(out, "0xc0000135") || strings.Contains(err.Error(), "0xc0000135") {
			hint = " MySQL 5.7 needs the Microsoft Visual C++ 2013 runtime (x64): install vcredist_x64.exe from Microsoft, then try again."
		}
		return rep, fmt.Errorf("mysqld --initialize failed: %v: %s%s", err, lastLines(out, 5), hint)
	}
	rep.Steps = append(rep.Steps, "databases created in "+dataDir)
	return rep, nil
}

// MariaDBPortInUse is MariaDB's port when MariaDB is installed, else 0.
func MariaDBPortInUse(root paths.Root, cfg config.Settings) int {
	if _, ok := dbserver.Get(root, cfg, dbserver.MariaDB); ok {
		return cfg.DBPort
	}
	return 0
}

// PickMySQLPort returns the first free port from 3306 other than avoid
// (MariaDB's port when it is installed).
func PickMySQLPort(avoid int) int {
	for p := 3306; p < 3400; p++ {
		if p != avoid && ports.Check(p) == nil {
			return p
		}
	}
	return 3399
}

// WriteMySQLIni writes my.ini for a MySQL version: loopback only, no
// binary log (it grows without end on a dev machine), no X Protocol port,
// performance schema off to save memory.
func WriteMySQLIni(root paths.Root, version string, port int) (string, error) {
	dataDir, ini := dbserver.Paths(root, dbserver.MySQL, version)
	if err := os.MkdirAll(filepath.Dir(ini), 0o755); err != nil {
		return "", err
	}
	base := root.RuntimeDir("mysql", version)
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by Ebur. Edits are overwritten.\n[mysqld]\n")
	fmt.Fprintf(&b, "basedir=\"%s\"\ndatadir=\"%s\"\nport=%d\nbind-address=127.0.0.1\n", filepath.ToSlash(base), filepath.ToSlash(dataDir), port)
	b.WriteString("character-set-server=utf8mb4\nperformance_schema=OFF\ninnodb_buffer_pool_size=128M\nmax_allowed_packet=256M\n")
	if strings.HasPrefix(version, "5.") {
		b.WriteString("collation-server=utf8mb4_unicode_ci\nexplicit_defaults_for_timestamp=ON\n")
	} else {
		// information_schema_stats_expiry=0: show current table sizes (MySQL 8
		// otherwise caches them for a day, so new tables read as 0 B).
		b.WriteString("skip-log-bin\nmysqlx=OFF\ninformation_schema_stats_expiry=0\n")
	}
	fmt.Fprintf(&b, "\n[client]\nport=%d\nhost=127.0.0.1\ndefault-character-set=utf8mb4\n", port)
	return ini, fsutil.WriteFileAtomic(ini, []byte(b.String()), 0o644)
}

// WriteClientCnf writes a client option file with the root login, so MySQL
// tools get the password without it showing on a command line (MYSQL_PWD
// is deprecated in MySQL 8). Pass it as the first option:
// --defaults-extra-file=<path>.
func WriteClientCnf(root paths.Root, kind dbserver.Kind, version string, port int, password string) (string, error) {
	_, ini := dbserver.Paths(root, kind, version)
	p := filepath.Join(filepath.Dir(ini), "client.cnf")
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return "", err
	}
	c := fmt.Sprintf("# Generated by Ebur: the local root login for this server's tools.\n[client]\nuser=root\npassword=\"%s\"\nhost=127.0.0.1\nport=%d\n", password, port)
	return p, fsutil.WriteFileAtomic(p, []byte(c), 0o600)
}

// TrimMySQL removes what MySQL does not need to run: debug symbols
// (*.pdb, 450-700 MB), import libraries (*.lib), C headers, and the debug
// builds of plugins (lib\plugin\debug). Programs, DLLs, plugins and share\
// stay. It returns the bytes freed and is safe to run again.
func TrimMySQL(dir string) (int64, error) {
	freed, err := TrimMariaDB(dir) // *.pdb, *.lib and include\
	debug := filepath.Join(dir, "lib", "plugin", "debug")
	if st, statErr := os.Lstat(debug); statErr == nil && st.IsDir() {
		filepath.WalkDir(debug, func(p string, d os.DirEntry, e error) error {
			if e == nil && !d.IsDir() {
				if fi, e := d.Info(); e == nil {
					freed += fi.Size()
				}
			}
			return nil
		})
		if rmErr := os.RemoveAll(debug); rmErr != nil && err == nil {
			err = rmErr
		}
	}
	return freed, err
}
