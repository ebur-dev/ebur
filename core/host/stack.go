const (
	listenAddr  = "127.0.0.1" // NFR-07
	httpPort    = 80
	httpsPort   = 443
	phpBasePort = 9100
)

// activeOrNewest returns the configured version if installed, else the
// newest installed one.
func activeOrNewest(root paths.Root, cfg config.Settings, runtime string) (string, error) {
	installed, err := runtimes.Installed(root, runtime)
	if err != nil {
		return "", err
	}
	if v := cfg.Active[runtime]; v != "" {
		for _, iv := range installed {
			if iv == v {
				return v, nil
			}
		}
		return "", &hinted{
			fmt.Sprintf("%s %s is set as active but is not installed", runtime, v),
			fmt.Sprintf("Run `ebur %s install %s`, or pick an installed version.", runtime, v),
		}
	}
	if len(installed) == 0 {
		example := "ebur install " + runtime
		if runtime == "php" {
			example = "ebur php install 8.4"
		}
		return "", &hinted{fmt.Sprintf("%s is not installed", runtime), "Run `" + example + "`."}
	}
	return installed[0], nil
}

// poolPort gives each installed PHP version a fixed block of ports, by
// its place among installed versions, oldest first. A pool's ports must
// not depend on which other versions are running: when a site pinned a
// new version, positional ports shifted the other pools and the reload
// restarted them, briefly interrupting unrelated sites (SITE-05).
func poolPort(installedNewestFirst []string, version string, size int) int {
	n := len(installedNewestFirst)
	for i, v := range installedNewestFirst {
		if v == version {
			return phpBasePort + (n-1-i)*size // oldest gets the first block
		}
	}
	return phpBasePort + n*size // not installed (should not happen): after all others
}

// optional is activeOrNewest for runtimes the stack can run without
// (MariaDB, Adminer): it returns "" when none is installed.
func optional(root paths.Root, cfg config.Settings, runtime string) (string, error) {
	if installed, _ := runtimes.Installed(root, runtime); len(installed) == 0 && cfg.Active[runtime] == "" {
		return "", nil
	}
	return activeOrNewest(root, cfg, runtime)
}

var reserved = sites.Reserved

// nginxStopGrace is how long Nginx gets to exit after "nginx -s stop"
// before it is ended (it normally exits within 0.2 s).
const nginxStopGrace = time.Second

var errNginxSlowStop = errors.New("nginx did not exit within a second of stop; ending it")

// mailpitSpec runs Mailpit on loopback only. Its own defaults listen on
// all interfaces ([::]), which would expose captured mail to the network
// (NFR-07); it would also check online for updates (NFR-17).
func mailpitSpec(root paths.Root, version string) supervisor.Spec {
	dir := root.RuntimeDir("mailpit", version)
	data := filepath.Join(root.Data(), "mailpit")
	os.MkdirAll(data, 0o755)
	return supervisor.Spec{
		Name: "mailpit",
		Path: filepath.Join(dir, proc.Exe("mailpit")),
		Args: []string{
			"--smtp", fmt.Sprintf("%s:%d", listenAddr, provision.MailSMTPPort),
			"--listen", fmt.Sprintf("%s:%d", listenAddr, provision.MailUIPort),
			"--database", filepath.Join(data, "mailpit.db"), // keep mail across restarts
			"--smtp-auth-accept-any",     // apps configured with any SMTP login just work
			"--smtp-auth-allow-insecure", // ...over plain local SMTP
			"--smtp-disable-rdns",
			"--disable-version-check",
		},
		Dir:     dir,
		LogFile: filepath.Join(root.Logs(), "mailpit.log"),
	}
}

// writeMailIni points PHP's mail() at Mailpit for every PHP version in
// use, or removes the setting when Mailpit is not installed. The user's
// php.ini is never edited.
func writeMailIni(scanDirs []string, on bool) error {
	ini := fmt.Sprintf("; Generated by Ebur (TOOL-03): PHP's mail() goes to Mailpit, never to real addresses.\nSMTP = %s\nsmtp_port = %d\nsendmail_from = \"ebur@localhost\"\n", listenAddr, provision.MailSMTPPort)
	for _, d := range scanDirs {
		p := filepath.Join(d, "ebur-mail.ini")
		if !on {
			os.Remove(p)
			continue
		}
		if err := fsutil.WriteFileAtomic(p, []byte(ini), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// mariadbSpec runs mariadbd with Ebur's my.ini, setting up the data folder
// first if it is missing.
func mariadbSpec(root paths.Root, version, password string, port int) (supervisor.Spec, error) {
	dir := root.RuntimeDir("mariadb", version)
	dataDir, _ := provision.MariaDBPaths(root, version)
	myIni, err := provision.WriteMyIni(root, version, port)
	if err != nil {
		return supervisor.Spec{}, err
	}
	// Installs made before Ebur trimmed MariaDB get trimmed here, once.
	if freed, err := provision.TrimMariaDB(dir); err != nil {
		log.Printf("mariadb: could not remove debug files: %v", err)
	} else if freed > 0 {
		log.Printf("mariadb: removed %d MB of debug and developer files", freed>>20)
	}
	if _, err := os.Stat(filepath.Join(dataDir, "mysql")); err != nil {
		if _, err := provision.Prepare(context.Background(), root, "mariadb", version, nil); err != nil {
			return supervisor.Spec{}, err
		}
		cfg, _ := config.Load(root.Config())
		password = cfg.DBRootPassword
	}
	defaults := "--defaults-file=" + filepath.ToSlash(myIni) // must be the first option
	admin := filepath.Join(dir, "bin", proc.Exe("mariadb-admin"))
	return supervisor.Spec{
		Name:    "mariadb",
		Path:    filepath.Join(dir, "bin", proc.Exe("mariadbd")),
		Args:    []string{defaults, "--console"},
		Dir:     dir,
		LogFile: filepath.Join(root.Logs(), "mariadb.log"),
		Stop: func(ctx context.Context, _ int) error {
			// A clean shutdown avoids InnoDB crash recovery on next start.
			cmd := exec.CommandContext(ctx, admin, defaults, "--user=root", "shutdown")
			cmd.Env = append(os.Environ(), "MYSQL_PWD="+password) // keeps it off the command line
			proc.Hide(cmd)
			return cmd.Run()
		},
	}, nil
}

// BuildStack is the production stack: Nginx in front of one php-cgi pool
// for the active PHP version, plus MariaDB and Adminer when installed.
func BuildStack(root paths.Root, cfg config.Settings) (Stack, error) {
	phpVer, err := activeOrNewest(root, cfg, "php")
	if err != nil {
		return Stack{}, err
	}
	nginxVer, err := activeOrNewest(root, cfg, "nginx")
	if err != nil {
		return Stack{}, err
	}
	if err := root.Ensure(); err != nil {
		return Stack{}, err
	}
	nginxDir := root.RuntimeDir("nginx", nginxVer)

	scanned, skipped, err := sites.Scan(root.WWW(), cfg.TLD)
	if err != nil {
		return Stack{}, err
	}
	// PHP-04: each site's .ebur or composer.json picks its PHP version.
	phpInstalled, _ := runtimes.Installed(root, "php")
	var found []sites.Site
	var choices []project.Choice
	for _, s := range scanned {
		if tool, ok := reserved[s.Name]; ok {
			skipped = append(skipped, sites.Skipped{Folder: s.Name, Reason: fmt.Sprintf("%s is reserved for %s; rename the folder", s.Host, tool)})
			continue
		}
		s.PHP = project.Resolve(s.Dir, phpInstalled, phpVer)
		choices = append(choices, s.PHP)
		found = append(found, s)
	}

	// One php-cgi pool per PHP version in use, each on its own port range;
	// the default version always runs (Adminer and new sites use it).
	var specs []supervisor.Spec
	var pools []php.Pool
	var scanDirs []string
	ports := []int{httpPort}
	for _, v := range project.Versions(phpVer, choices) {
		port := poolPort(phpInstalled, v, cfg.PHPPoolSize)
		dir := root.RuntimeDir("php", v)
		ini, err := php.EnsureINI(root.Etc(), dir, v, filepath.Join(root.Data(), "tmp"))
		if err != nil {
			return Stack{}, err
		}
		scanDir := filepath.Join(root.Etc(), "php", v, "conf.d")
		if err := os.MkdirAll(scanDir, 0o755); err != nil {
			return Stack{}, err
		}
		pool := php.Pool{Version: v, Dir: dir, INI: ini, BasePort: port, Size: cfg.PHPPoolSize, LogDir: root.Logs(), ScanDir: scanDir}
		s, err := pool.Specs()
		if err != nil {
			return Stack{}, err
		}
		specs = append(specs, s...)
		pools = append(pools, pool)
		scanDirs = append(scanDirs, scanDir)
		ports = append(ports, pool.Ports()...)
	}
	info := Info{PHP: phpVer, Nginx: nginxVer, Sites: found, Skipped: skipped}
	for _, p := range pools {
		info.PHPVersions = append(info.PHPVersions, p.Version)
	}

	dbVer, err := optional(root, cfg, "mariadb")
	if err != nil {
		return Stack{}, err
	}
	if dbVer != "" {
		s, err := mariadbSpec(root, dbVer, cfg.DBRootPassword, cfg.DBPort)
		if err != nil {
			return Stack{}, err
		}
		specs = append(specs, s)
		ports = append(ports, cfg.DBPort)
		info.MariaDB = dbVer
	}
	served := found
	adminerVer, err := optional(root, cfg, "adminer")
	if err != nil {
		return Stack{}, err
	}
	if adminerVer != "" { // TOOL-01: Adminer is served like any other site
		tool := sites.Site{Name: "db", Host: "db." + cfg.TLD, DocRoot: root.RuntimeDir("adminer", adminerVer)}
		served = append(append([]sites.Site(nil), found...), tool)
		info.Adminer = "http://" + tool.Host
	}

	// TOOL-03: Mailpit catches everything PHP sends; mail.<tld> shows it.
	var proxies []nginxconf.Proxy
	mailVer, err := optional(root, cfg, "mailpit")
	if err != nil {
		return Stack{}, err
	}
	if mailVer != "" {
		specs = append(specs, mailpitSpec(root, mailVer))
		ports = append(ports, provision.MailSMTPPort, provision.MailUIPort)
		proxies = append(proxies, nginxconf.Proxy{Host: "mail." + cfg.TLD, Target: fmt.Sprintf("%s:%d", listenAddr, provision.MailUIPort)})
		info.Mail = "http://mail." + cfg.TLD
	}
	if err := writeMailIni(scanDirs, mailVer != ""); err != nil {
		return Stack{}, err
	}

	listen := listenAddr + ":" + strconv.Itoa(httpPort)
	tempDir := filepath.Join(root.Data(), "nginx-temp")
	if err := os.MkdirAll(tempDir, 0o755); err != nil {
		return Stack{}, err
	}
	nc := nginxconf.Config{
		NginxDir: nginxDir,
		LogDir:   root.Logs(),
		TempDir:  tempDir,
		PIDFile:  filepath.Join(root.Data(), "nginx.pid"),
		Listen:   listen,
		Sites:    served,
		Pools:    pools,
		Proxies:  proxies,
	}
	shareSpecs, shareServers, err := shareParts(root, cfg, found)
	if err != nil {
		return Stack{}, err
	}
	specs = append(specs, shareSpecs...)
	nc.Shares = shareServers
	tlsHosts := make([]string, 0, len(served)+len(proxies))
	for _, s := range served {
		tlsHosts = append(tlsHosts, s.Host)
	}
	for _, p := range proxies {
		tlsHosts = append(tlsHosts, p.Host)
	}
	if err := setupTLS(root, cfg, &nc, tlsHosts, scanDirs); err != nil {
		return Stack{}, err
	}
	if nc.TLSListen != "" {
		ports = append(ports, httpsPort)
		info.HTTPS = true
	}
	conf := nginxconf.Render(nc)
	nginxExe := filepath.Join(nginxDir, "nginx.exe")
	// nginx resolves its default log path against the prefix before it
	// reads the config, so the prefix is the Ebur root (which has logs\).
	prefix := filepath.ToSlash(root.Dir()) + "/"
	confPath := filepath.Join(root.Etc(), "nginx", "nginx.conf")
	if err := writeTested(confPath, conf, nginxExe, prefix); err != nil {
		return Stack{}, err
	}
	nginxArgs := []string{"-p", prefix, "-c", filepath.ToSlash(confPath)}
	specs = append(specs, supervisor.Spec{
		Name:    "nginx",
		Path:    nginxExe,
		Args:    nginxArgs,
		Dir:     nginxDir,
		LogFile: filepath.Join(root.Logs(), "nginx-console.log"),
		Stop: func(ctx context.Context, pid int) error {
			// Fast stop: a graceful "quit" waits for open connections (a
			// browser's keep-alive, a slow request) and made restarts take
			// 10 s; a local dev server has nothing to drain.
			cmd := exec.CommandContext(ctx, nginxExe, append(nginxArgs, "-s", "stop")...)
			cmd.Dir = nginxDir
			proc.Hide(cmd)
			if err := cmd.Run(); err != nil {
				return err
			}
			// Even "stop" takes about 5 s on Windows while any connection is
			// mid-request (a half-sent request, a slow PHP page). Give it a
			// second, then report failure so the supervisor ends it and its
			// workers, which frees ports 80 and 443 at once.
			if proc.WaitExit(pid, nginxStopGrace) {
				return nil
			}
			return errNginxSlowStop
		},
	})

	info.Listen = listen
	reload := func(ctx context.Context) error {
		cmd := exec.CommandContext(ctx, nginxExe, append(nginxArgs, "-s", "reload")...)
		cmd.Dir = nginxDir
		proc.Hide(cmd)
		return cmd.Run()
	}
	return Stack{Specs: specs, Ports: ports, Info: info, Reload: reload}, nil
}

// setupTLS enables HTTPS once the user has created the local CA with
// `ebur ssl install` (SSL-01 consent). It issues or renews a certificate
// per served host (SSL-02), refreshes the CRL, and points PHP at a bundle
// of public roots plus the Ebur CA (SSL-04). Without a CA it removes the
// PHP CA settings so nothing points at missing files.
func setupTLS(root paths.Root, cfg config.Settings, nc *nginxconf.Config, hosts []string, scanDirs []string) error {
	dir := certs.Dir(root.SSL())
	if !dir.Exists() {
		for _, d := range scanDirs {
			os.Remove(filepath.Join(d, "ebur-ssl.ini"))
		}
		return nil
	}
	ca, err := dir.LoadCA()
	if err != nil {
		return &hinted{"local CA is damaged: " + err.Error(), "Run `ebur ssl uninstall`, then `ebur ssl install`."}
	}
	crl, err := dir.EnsureCRL(ca)
	if err != nil {
		return err
	}
	crlURL := fmt.Sprintf("http://%s:%d%s", listenAddr, httpPort, certs.CRLPath)
	nc.TLS = map[string]nginxconf.TLSPair{}
	for _, host := range hosts {
		c, k, err := dir.EnsureSite(ca, host, crlURL)
		if err != nil {
			return &hinted{err.Error(), "Run `ebur ssl uninstall` and `ebur ssl install` to make a CA for the current TLD."}
		}
		nc.TLS[host] = nginxconf.TLSPair{Cert: c, Key: k}
	}
	nc.TLSListen = listenAddr + ":" + strconv.Itoa(httpsPort)
	nc.CRLFile, nc.CRLPath = crl, certs.CRLPath

	var roots []byte
	if v, _ := optional(root, cfg, "cacert"); v != "" {
		roots, _ = os.ReadFile(filepath.Join(root.RuntimeDir("cacert", v), "cacert.pem"))
	}
	bundle, err := dir.WriteBundle(ca, roots)
	if err != nil {
		return err
	}
	b := filepath.ToSlash(bundle)
	ini := fmt.Sprintf("; Generated by Ebur (SSL-04): trust public roots and the Ebur CA.\ncurl.cainfo = \"%s\"\nopenssl.cafile = \"%s\"\n", b, b)
	for _, d := range scanDirs { // every PHP version in use (PHP-04)
		if err := fsutil.WriteFileAtomic(filepath.Join(d, "ebur-ssl.ini"), []byte(ini), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// writeTested writes conf next to path, checks it with `nginx -t`, and
// only then replaces path. A bad config never replaces a working one
// (NFR-10).
func writeTested(path, conf, nginxExe, prefix string) error {
	candidate := path + ".new"
	if err := fsutil.WriteFileAtomic(candidate, []byte(conf), 0o644); err != nil {
		return err
	}
	cmd := exec.Command(nginxExe, "-t", "-p", prefix, "-c", filepath.ToSlash(candidate))
	proc.Hide(cmd)
	if out, err := cmd.CombinedOutput(); err != nil {
		return &hinted{
			fmt.Sprintf("generated Nginx config failed its test; the previous config was kept: %s", lastLine(string(out))),
			"Check templates\\ for recent edits, then run `ebur doctor`. The rejected config is at " + candidate,
		}
	}
	return fsutil.Rename(candidate, path)
}

func lastLine(s string) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	return strings.TrimSpace(lines[len(lines)-1])
}
