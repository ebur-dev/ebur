// redisConf is the config Ebur starts Redis with (SVC-05): loopback only,
// data kept in data\redis\ and saved to disk now and then, so cached data
// and queued jobs survive a restart. dataDir is relative to the config's
// folder: the MSYS2 build of Redis does not understand "C:/..." paths
// (it read them as relative), so Redis runs from etc\redis\ and every
// path it sees is relative.
func redisConf(dataDir string) string {
	return fmt.Sprintf(`# Generated by Ebur (SVC-05). Edits are overwritten.
bind %s
port %d
protected-mode yes
daemonize no
logfile ""
dir "%s"
dbfilename dump.rdb
save 3600 1 300 100 60 10000
appendonly no
`, listenAddr, provision.RedisPort, filepath.ToSlash(dataDir))
}

// redisSpec runs redis-server with Ebur's config. Stop asks Redis to shut
// down, which saves its data first.
func redisSpec(root paths.Root, version string) (supervisor.Spec, error) {
	dir := root.RuntimeDir("redis", version)
	data := filepath.Join(root.Data(), "redis")
	if err := os.MkdirAll(data, 0o755); err != nil {
		return supervisor.Spec{}, err
	}
	confDir := filepath.Join(root.Etc(), "redis")
	if err := os.MkdirAll(confDir, 0o755); err != nil {
		return supervisor.Spec{}, err
	}
	rel, err := filepath.Rel(confDir, data)
	if err != nil {
		return supervisor.Spec{}, err
	}
	if err := fsutil.WriteFileAtomic(filepath.Join(confDir, "redis.conf"), []byte(redisConf(rel)), 0o644); err != nil {
		return supervisor.Spec{}, err
	}
	cli := filepath.Join(dir, proc.Exe("redis-cli"))
	return supervisor.Spec{
		Name:    "redis",
		Path:    filepath.Join(dir, proc.Exe("redis-server")),
		Args:    []string{"redis.conf"}, // relative to Dir, see redisConf
		Dir:     confDir,
		LogFile: filepath.Join(root.Logs(), "redis.log"),
		Stop: func(ctx context.Context, _ int) error {
			cmd := exec.CommandContext(ctx, cli, "-h", listenAddr, "-p", strconv.Itoa(provision.RedisPort), "shutdown")
			cmd.Dir = dir
			proc.Hide(cmd)
			return cmd.Run()
		},
	}, nil
}

// writeRedisIni loads the phpredis extension in every installed PHP
// version that has a build for it, through Ebur's conf.d (the user's
// php.ini is never edited). Without Redis, or without a build for that
// PHP version, the file is removed.
func writeRedisIni(root paths.Root, redisOn bool) error {
	installed, _ := runtimes.Installed(root, "php")
	for _, v := range installed {
		scan := filepath.Join(root.Etc(), "php", v, "conf.d")
		p := filepath.Join(scan, "ebur-redis.ini")
		dll, ok := provision.PHPRedisDLL(root, v)
		if !redisOn || !ok {
			os.Remove(p)
			continue
		}
		if err := os.MkdirAll(scan, 0o755); err != nil {
			return err
		}
		ini := fmt.Sprintf("; Generated by Ebur (SVC-05): the phpredis extension, for Redis on 127.0.0.1:%d.\nextension = \"%s\"\n", provision.RedisPort, filepath.ToSlash(dll))
		if err := fsutil.WriteFileAtomic(p, []byte(ini), 0o644); err != nil {
			return err
		}
	}
	return nil
}
